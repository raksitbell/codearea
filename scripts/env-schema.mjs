import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { randomBytes } from "node:crypto";

function makeJwtSecret() {
  return randomBytes(32).toString("hex");
}

function parseExistingKeys(filePath) {
  if (!existsSync(filePath)) {
    return new Set();
  }

  const content = readFileSync(filePath, "utf8");
  const keys = new Set();

  for (const line of content.split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=/);
    if (match) {
      keys.add(match[1]);
    }
  }

  return keys;
}

export function parseEnvValues(filePath) {
  if (!existsSync(filePath)) {
    return {};
  }

  const content = readFileSync(filePath, "utf8");
  const values = {};

  for (const line of content.split(/\r?\n/)) {
    const match = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (!match) {
      continue;
    }

    values[match[1]] = match[2];
  }

  return values;
}

function renderEntry(entry) {
  const lines = [];

  if (entry.comment) {
    for (const line of entry.comment) {
      lines.push(`# ${line}`);
    }
  }

  lines.push(`${entry.key}=${entry.value}`);
  return lines.join("\n");
}

function renderCommentedExample(entry) {
  const lines = [];

  if (entry.comment) {
    for (const line of entry.comment) {
      lines.push(`# ${line}`);
    }
  }

  lines.push(`# ${entry.key}=${entry.value}`);
  return lines.join("\n");
}

function renderValueEntry(entry, value) {
  const lines = [];

  if (entry.comment) {
    for (const line of entry.comment) {
      lines.push(`# ${line}`);
    }
  }

  lines.push(`${entry.key}=${value}`);
  return lines.join("\n");
}

function renderEnvFile(schema) {
  const parts = [
    `# Auto-generated by npm run setup:env`,
    `# Target: ${schema.targetLabel}`,
    `# Active vars below are required or intentionally customized for local development.`,
  ];

  for (const section of schema.sections) {
    const activeEntries = section.entries.filter((entry) => !entry.skipByDefault);
    const skippedEntries = section.entries.filter((entry) => entry.skipByDefault);

    if (activeEntries.length === 0 && skippedEntries.length === 0) {
      continue;
    }

    parts.push("");
    parts.push(`# ${section.title}`);

    if (activeEntries.length > 0) {
      for (const entry of activeEntries) {
        parts.push(renderEntry(entry));
        parts.push("");
      }
      parts.pop();
    }

    if (skippedEntries.length > 0) {
      parts.push("");
      parts.push(`# Optional defaults skipped for now.`);
      parts.push(`# Uncomment only when you need to override app fallback behavior.`);

      for (const entry of skippedEntries) {
        parts.push(renderCommentedExample(entry));
        parts.push("");
      }
      parts.pop();
    }
  }

  return `${parts.join("\n").trim()}\n`;
}

function appendMissingEntries(schema, missingEntries) {
  const chunks = [
    "",
    "# Added by npm run setup:env",
  ];

  for (const entry of missingEntries) {
    chunks.push(renderEntry(entry));
    chunks.push("");
  }

  appendFileSync(schema.targetPath, `${chunks.join("\n").trimEnd()}\n`);
}

