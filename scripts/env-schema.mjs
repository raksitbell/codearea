export function ensureEnvSchemas(rootDir) {
  const schemas = createEnvSchemas(rootDir);

  for (const schema of schemas) {
    const allEntries = schema.sections.flatMap((section) => section.entries);

    if (!existsSync(schema.targetPath)) {
      writeFileSync(schema.targetPath, renderEnvFile(schema), "utf8");
      console.log(`created ${path.relative(rootDir, schema.targetPath)}`);
      continue;
    }

    const existingKeys = parseExistingKeys(schema.targetPath);
    const missingEntries = allEntries.filter(
      (entry) => !entry.skipByDefault && !existingKeys.has(entry.key)
    );

    if (missingEntries.length === 0) {
      console.log(`skip ${path.relative(rootDir, schema.targetPath)}: already has required keys`);
      continue;
    }

    appendMissingEntries(schema, missingEntries);
    console.log(
      `updated ${path.relative(rootDir, schema.targetPath)} with missing keys: ${missingEntries
        .map((entry) => entry.key)
        .join(", ")}`
    );
  }
}

export function writeEnvFile(schema, selectedValues = {}, existingValues = {}) {
  const parts = [
    `# Auto-generated by npm run setup:env`,
    `# Target: ${schema.targetLabel}`,
    `# Active vars below are required or intentionally customized for local development.`,
  ];

  for (const section of schema.sections) {
    const activeBlocks = [];
    const skippedBlocks = [];

    for (const entry of section.entries) {
      const value = selectedValues[entry.key] ?? existingValues[entry.key];

      if (value && String(value).trim() !== "") {
        activeBlocks.push(renderValueEntry(entry, value));
        continue;
      }

      if (entry.skipByDefault) {
        skippedBlocks.push(renderCommentedExample(entry));
      }
    }

    if (activeBlocks.length === 0 && skippedBlocks.length === 0) {
      continue;
    }

    parts.push("");
    parts.push(`# ${section.title}`);

    for (const block of activeBlocks) {
      parts.push(block);
      parts.push("");
    }
    if (activeBlocks.length > 0) {
      parts.pop();
    }

    if (skippedBlocks.length > 0) {
      parts.push("");
      parts.push(`# Optional defaults skipped for now.`);
      parts.push(`# Uncomment only when you need to override app fallback behavior.`);

      for (const block of skippedBlocks) {
        parts.push(block);
        parts.push("");
      }
      parts.pop();
    }
  }

  writeFileSync(schema.targetPath, `${parts.join("\n").trim()}\n`, "utf8");
}
